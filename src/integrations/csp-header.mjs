// Appends a Content-Security-Policy for every page to dist/_headers, with the hashes of every inline
// script in the build. Cloudflare Pages applies all matching _headers rules, so this sits alongside
// the /* block from public/_headers. An embedded video iframe (examples `video` field) would need its
// host added to frame-src.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { inlineScriptHashes, contentSecurityPolicy } from "../lib/csp.mjs";

// Cloudflare Pages ignores _headers lines longer than this.
const LINE_MAX = 2000;

function htmlFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? htmlFiles(p) : d.name.endsWith(".html") ? [p] : [];
  });
}

export default function cspHeader() {
  return {
    name: "csp-header",
    hooks: {
      "astro:build:done": ({ dir, logger }) => {
        const dist = fileURLToPath(dir);
        const hashes = new Set(htmlFiles(dist).flatMap((f) => inlineScriptHashes(fs.readFileSync(f, "utf8"))));
        const line = `  Content-Security-Policy: ${contentSecurityPolicy([...hashes].sort())}`;
        if (line.length > LINE_MAX) throw new Error(`CSP header is ${line.length} characters; Pages allows ${LINE_MAX}`);
        fs.appendFileSync(path.join(dist, "_headers"), `\n# Generated by src/integrations/csp-header.mjs\n/*\n${line}\n`);
        logger.info(`Content-Security-Policy with ${hashes.size} inline script hashes: OK`);
      },
    },
  };
}
